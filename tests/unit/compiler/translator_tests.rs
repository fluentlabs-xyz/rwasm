use super::*;

macro_rules! assert_unsupported {
    ($visitor:ident; $($method:ident($($arg:expr),*)),+ $(,)?) => {
        $(
            assert!(matches!(
                VisitOperator::$method(&mut $visitor, $($arg),*),
                Err(CompilationError::NotSupportedExtension)
            ));
        )+
    };
}

